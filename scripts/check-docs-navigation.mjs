import {createRequire} from 'node:module';
import {readdirSync} from 'node:fs';
import {join, relative, resolve} from 'node:path';

const root = resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const sidebars = require(join(root, 'sidebars.js'));
const {isInternalResourceDocId} = require(join(root, 'scripts', 'api-doc-scope.cjs'));
const sidebarDocIds = new Set();

function collectSidebarItems(items) {
  for (const item of items) {
    if (typeof item === 'string') sidebarDocIds.add(item);
    else if (item.type === 'doc') sidebarDocIds.add(item.id);
    else if (item.type === 'autogenerated') {
      const directory = join(root, 'docs', item.dirName);
      for (const id of collectMarkdown(directory)) sidebarDocIds.add(id);
    }
    else if (item.type === 'category') {
      if (item.link?.type === 'doc') sidebarDocIds.add(item.link.id);
      collectSidebarItems(item.items);
    }
  }
}

function collectMarkdown(directory) {
  return readdirSync(directory, {withFileTypes: true}).flatMap((entry) => {
    const file = join(directory, entry.name);
    if (entry.isDirectory()) return collectMarkdown(file);
    if (!entry.name.endsWith('.md') && !entry.name.endsWith('.mdx')) return [];
    return [relative(join(root, 'docs'), file).replace(/\\/g, '/').replace(/\.mdx?$/, '')];
  });
}

for (const items of Object.values(sidebars)) collectSidebarItems(items);

const markdownDocIds = new Set(collectMarkdown(join(root, 'docs')).filter((id) => !isInternalResourceDocId(id)));
const hiddenDocs = [...markdownDocIds].filter((id) => !sidebarDocIds.has(id));
const invalidSidebarIds = [...sidebarDocIds].filter((id) => !markdownDocIds.has(id));

if (hiddenDocs.length || invalidSidebarIds.length) {
  if (hiddenDocs.length) console.error(`Sidebar-da olmayan sənədlər:\n- ${hiddenDocs.join('\n- ')}`);
  if (invalidSidebarIds.length) console.error(`Mövcud olmayan sidebar id-ləri:\n- ${invalidSidebarIds.join('\n- ')}`);
  process.exitCode = 1;
} else {
  console.log(`Navigation audit passed: ${markdownDocIds.size} sənədin hamısı sidebar-dadır.`);
}
